##ORDEM DE PRECEDÊNCIA
# Definição: é a ordem na qual os operadores serão executados
# 1 Expressões dentro de parenteses
# 2 Em seguida vem as pontenciações
# 3 Em terceiro lugar vem a multiplicação, a divisão normal, 
# a divisão inteira e o resto da divisão. No caso de ter mais de um deles você resolve quem aparecer primeiro.
# 4 E por último a soma e a subtração

